"""Regenerate web/js/icons.js from lucide-static 0.525.0 (ISC license).

The Next.js UI imported ~45 icons from lucide-react 0.525.0. This script
fetches the same icons from the lucide-static package and emits them as a
single vanilla-JS module, so the port keeps the exact original iconography
without any npm dependency. Run from the repo root:

    python3 scripts/fetch_icons.py
"""

import json
import re
import sys
import urllib.request

BASE = "https://unpkg.com/lucide-static@0.525.0/icons/{}.svg"

# React export name -> candidate static file names (lucide renamed some icons
# between major versions; the react package kept the old names as aliases).
